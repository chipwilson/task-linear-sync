/**
 * Internal content model (research R4; data-model § 8): the terminator-preserving line
 * array shared by parsing AND rendering "so parsing and rendering cannot disagree about
 * line numbering or bytes". One forward pass marks fenced regions; leading tabs are
 * expanded into `indentWidth` (nesting/extent comparisons) while `originalIndent` keeps
 * the raw bytes for the renderer.
 *
 * Purity: string→value functions only — zero filesystem access, zero clock.
 */

/** One physical line with its terminator bytes preserved separately. */
export interface ContentLine {
  /** 1-based line number. */
  readonly number: number;
  /** Raw line text WITHOUT its terminator. */
  readonly text: string;
  /** Terminator bytes: "\r\n", "\n", or "" for a final unterminated line. Never regenerated by the renderer, only carried (FR-012). */
  readonly terminator: string;
  /** Raw leading-whitespace bytes (used verbatim by the renderer, FR-011). */
  readonly originalIndent: string;
  /** Visual indent column after expanding leading tabs to the configured tab width. */
  readonly indentWidth: number;
  /** True inside a fenced region INCLUDING the fence delimiter lines (R4: interiors "and the fence delimiter lines themselves"). */
  readonly inFence: boolean;
}

/**
 * Split content into terminator-preserving lines. Terminators are never normalized:
 * mixed `\r\n`/`\n` files and a final unterminated line reproduce exactly when the
 * renderer rejoins `text + terminator` (FR-012). A trailing newline terminates the last
 * real line and creates no phantom line.
 */
export function splitLines(content: string, tabWidth: number): ContentLine[] {
  if (content === "") return [];
  const raw = content.split(/(?<=\n)/);
  if (raw.at(-1) === "") raw.pop();

  const fenceOpenRe = /^ {0,3}(`{3,}|~{3,})/u;
  const lines: ContentLine[] = [];
  let fenceChar: string | undefined;
  let fenceLength = 0;

  raw.forEach((entry, index) => {
    let text = entry;
    let terminator = "";
    if (text.endsWith("\r\n")) {
      terminator = "\r\n";
      text = text.slice(0, -2);
    } else if (text.endsWith("\n")) {
      terminator = "\n";
      text = text.slice(0, -1);
    }

    const inFence = fenceChar !== undefined; // a line inside an open fence (its body)
    const openMatch = fenceOpenRe.exec(text);
    let lineInFence = inFence;
    if (fenceChar !== undefined) {
      // Closing fence: same char, length >= opening length; the delimiter line itself is inFence.
      const closeRe = new RegExp(`^ {0,3}${fenceChar === "`" ? "`" : "~"}{${fenceLength},}\\s*$`, "u");
      if (closeRe.test(text)) {
        fenceChar = undefined;
        fenceLength = 0;
      }
      lineInFence = true;
    } else if (openMatch?.[1]) {
      fenceChar = openMatch[1][0];
      fenceLength = openMatch[1].length;
      lineInFence = true; // the opening delimiter line is itself non-task text
    }

    lines.push({
      number: index + 1,
      text,
      terminator,
      originalIndent: leadingWhitespace(text),
      indentWidth: visualIndentWidth(text, tabWidth),
      inFence: lineInFence,
    });
  });

  return lines;
}

/** Raw leading whitespace bytes (spaces/tabs) of a line. */
function leadingWhitespace(text: string): string {
  const m = /^[ \t]*/u.exec(text);
  return m ? m[0] : "";
}

/** Visual column after expanding leading tabs to `tabWidth` (tabs: next multiple of tabWidth). */
export function visualIndentWidth(text: string, tabWidth: number): number {
  let column = 0;
  for (const ch of leadingWhitespace(text)) {
    column = ch === "\t" ? column + (tabWidth - (column % tabWidth)) : column + 1;
  }
  return column;
}

/** Fenced-region query (T012 "export the type for internal use + fence-set queries"). */
export function lineIsFenced(lines: readonly ContentLine[], lineNumber: number): boolean {
  return lines[lineNumber - 1]?.inFence === true;
}

/** Markdown heading level (1–6) when the line text is an ATX heading line, else undefined. */
export function headingLevelOf(text: string): number | undefined {
  const m = /^ {0,3}(#{1,6})(?:[ \t]|$)/u.exec(text);
  if (!m?.[1]) return undefined;
  return m[1].length;
}

/**
 * Checkbox recognition from the configured `flatChecklistMarkers` literals
 * (parsing-api rule 1: "a checkbox line (`flatChecklistMarkers` prefix after leading
 * whitespace)"). Returns the matched marker bytes, parsed state, and the line remainder.
 */
export interface CheckboxMatch {
  /** Raw bytes consumed: indent + marker + following whitespace. */
  readonly prefix: string;
  /** The matched configured marker literal (indent excluded). */
  readonly marker: string;
  /** State byte inside the brackets as written (" ", "x", or "X"). */
  readonly stateChar: string;
  readonly checked: boolean;
  /** Line remainder after the marker prefix. */
  readonly rest: string;
}

export function matchCheckbox(text: string, markers: readonly string[]): CheckboxMatch | undefined {
  for (const marker of markers) {
    const m = new RegExp(`^([ \\t]*)${escapeRegExp(marker)}(?=[ \\t]|$)`, "u").exec(text);
    if (!m) continue;
    const indent = m[1] ?? "";
    const afterMarker = text.slice(indent.length + marker.length);
    const gapMatch = /^[ \t]*/u.exec(afterMarker);
    const gap = gapMatch ? gapMatch[0] : "";
    const stateMatch = /\[(.)\]/u.exec(marker);
    const stateChar = stateMatch?.[1] ?? " ";
    return {
      prefix: indent + marker + gap,
      marker,
      stateChar,
      checked: stateChar === "x" || stateChar === "X",
      rest: afterMarker.slice(gap.length),
    };
  }
  return undefined;
}

/** Replace the state byte of a marker literal (renderer: "set from assignment or retain", FR-011). */
export function markerWithState(marker: string, stateChar: string): string {
  return marker.replace(/(?<=\[).(?=\])/u, stateChar);
}

/** Escape a literal for embedding in a RegExp. */
export function escapeRegExp(literal: string): string {
  return literal.replace(/[.*+?^${}()|[\]\\]/gu, "\\$&");
}

/**
 * Module-local built-in default for a leading local-task-ID span on checklist lines and
 * inside heading title spans (research R2: "the built-in defaults live as module-local
 * constants in `src/parsing/`"; parsing-api rule 6: "a leading local-ID pattern on
 * checklist lines is likewise recorded as `localTaskId`"). Requires a digit and a
 * separating punctuation mark so ordinary sentence text never parses as an ID span
 * (`Task 2.1:`, `1.2.3:`, `T001 —`).
 */
export const LOCAL_ID_SPAN_RE =
  /^(?<id>(?:[A-Za-z][A-Za-z0-9-]*[ \t]+)?[0-9]+(?:\.[0-9]+)*[ \t]*[.:—–-]|[A-Za-z][A-Za-z0-9-]*\d+[ \t]*[.:—–-])[ \t]+/u;

/** Strip a leading local-ID span, returning [idWithoutSeparator, remainder] when present. */
export function stripLeadingLocalId(rest: string): [id: string, remainder: string] | undefined {
  const m = LOCAL_ID_SPAN_RE.exec(rest);
  const id = m?.groups?.id;
  if (!m || !id) return undefined;
  return [id.replace(/[ \t]*[.:—–-]$/u, "").trim(), rest.slice(m[0].length)];
}
