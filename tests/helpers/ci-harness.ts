/** Repository root (compiled helpers live at build/tests/helpers → three up). */
const pkgRoot = fileURLToPath(new URL("../../../", import.meta.url));

/** Absolute path of a built wrapper entrypoint. */
export const CI_MAIN_PATH = join(pkgRoot, "dist", "ci", "main.js");

/** Absolute path of a fixture report under tests/fixtures/ci/reports/. */
export function fixtureReport(name: string): string {
  return join(pkgRoot, "tests", "fixtures", "ci", "reports", name);
}

/** Copy a fixture report into a hermetic temp dir; returns the copy's path. */
export function copyFixtureReport(name: string, destDir: string): string {
  const dest = join(destDir, name);
  copyFileSync(fixtureReport(name), dest);
  return dest;
}

// ──────────────────────────────────────────────────────────────── writeCliEntry

export interface WriteCliEntryOptions {
  /** Absolute path of the `cli-entry.mjs` file to emit. */
  readonly entryPath: string;
  /** Absolute world directory (world.json + repo/), e.g. `cliWorldDir("…")`. */
  readonly worldDir: string;
  /** JSONL file each invocation's argv is appended to (spawn census). */
  readonly censusPath?: string;
  /** Extra `ConfigOverrides` merged over world.json `config`. */
  readonly config?: ConfigOverrides;
  /** Fixed-clock start (default: world.json `clock` else harness default). */
  readonly start?: string;
  /** Shared state dir so successive invocations see the same state. */
  readonly stateDir?: string;
}

/**
 * Emit a fake published-CLI entry (research R3 target). The wrapper spawns it
 * exactly like the real bin: `node cli-entry.mjs <command> <repo> [--config f]`.
 */
export function writeCliEntry(entryPath: string, opts: WriteCliEntryOptions): void {
  const dist = (rel: string): string => `file://${resolve(pkgRoot, "dist", rel)}`;
  const load = (selfRef: string, rel: string): string =>
    `await loadModule(${JSON.stringify(selfRef)}, ${JSON.stringify(dist(rel))})`;
  const entry = `#!/usr/bin/env node
// Generated by tests/helpers/ci-harness.ts writeCliEntry — fake published bin.
import { createHash } from "node:crypto";
import { appendFileSync, cpSync, existsSync, mkdirSync, mkdtempSync, readFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

async function loadModule(selfRef, absUrl) {
  try {
    return await import(selfRef);
  } catch {
    return await import(absUrl);
  }
}

const cli = await ${load("task-linear-sync/cli", "cli/index.js")};
const trackerTesting = await ${load("task-linear-sync/tracker/testing", "tracker/testing/index.js")};
const configMod = await ${load("task-linear-sync/config", "config/index.js")};
const stateMod = await ${load("task-linear-sync/state", "state/index.js")};
const engineMod = await ${load("task-linear-sync/engine", "engine/index.js")};

if (${JSON.stringify(opts.censusPath ?? "")} !== "") {
  appendFileSync(${JSON.stringify(opts.censusPath ?? "")}, JSON.stringify(process.argv.slice(2)) + "\\n");
}

const worldDir = ${JSON.stringify(resolve(opts.worldDir))};
const worldDoc = JSON.parse(readFileSync(join(worldDir, "world.json"), "utf8"));
const root = mkdtempSync(join(tmpdir(), "tls-013-entry-"));
const repositoryRoot = join(root, "repo");
if (existsSync(join(worldDir, "repo"))) cpSync(join(worldDir, "repo"), repositoryRoot, { recursive: true });
else mkdirSync(repositoryRoot, { recursive: true });
const stateDir = ${opts.stateDir === undefined ? 'join(root, "state")' : JSON.stringify(resolve(opts.stateDir))};

const startIso = ${JSON.stringify(opts.start ?? null)} ?? worldDoc.clock ?? "2026-01-01T00:00:00.000Z";
const clock = stateMod.fixedClock(new Date(startIso));
const loadConfig = ({ repositoryRoot: repoRoot, configFile }) =>
  configMod.loadConfig({
    repositoryRoot: repoRoot,
    ...(configFile === undefined || configFile === "" ? {} : { configFile }),
    overrides: { ...(worldDoc.config ?? {}), ...${JSON.stringify(opts.config ?? {})}, stateDirectory: stateDir },
  });
const config = loadConfig({ repositoryRoot });

const fake = trackerTesting.createFakeLinearPort({
  teams: worldDoc.teams ?? [],
  issues: worldDoc.issues ?? [],
  attachments: worldDoc.attachments ?? [],
});
const state = stateMod.createStateStore({ repositoryRoot, config, clock });
await state.ensure();

const keyValue = createHash("sha256")
  .update("task-linear-sync/013-entry/test-manifest-key/" + config.manifestKeyId)
  .digest("hex");
const keyBytes = Buffer.from(keyValue, "hex");
const keyProvider = { getKey: async (keyId) => (keyId === config.manifestKeyId ? keyBytes : null) };

const stdout = [];
const stderr = [];
const context = {
  cwd: repositoryRoot,
  env: { [config.manifestKeyEnvVarName]: keyValue },
  stdout: (line) => stdout.push(line),
  stderr: (line) => stderr.push(line),
  clock,
  loadConfig,
  makePort: () => fake,
  makeScreener: (cfg) => engineMod.createDefaultSecurityScreener(cfg),
  makeEngine: (deps) => engineMod.createSyncEngine(deps, { keyProvider }),
  makeState: () => state,
  queueSurface: cli.createDefaultQueueSurface(),
};

// argv from the caller: [command, repo, ...flags] — RAW stdout posture (no prefixes).
const argv = process.argv.slice(2);
const outcome = await cli.runCli(argv, context);
for (const line of stdout) process.stdout.write(line + "\\n");
for (const line of stderr) process.stderr.write(line + "\\n");
process.exitCode = outcome.exitCode;
`;
  writeFileSync(entryPath, entry, "utf8");
}

// ──────────────────────────────────────────────────────────────── runWrapper

export interface RunWrapperOptions {
  /** Env view for the spawn (hermetic: parent contributes PATH only). */
  readonly env?: Readonly<Record<string, string | undefined>>;
  /** Wrapper entry (default: built `dist/ci/main.js`). */
  readonly entry?: string;
  /** Spawn cwd (default: repository root). */
  readonly cwd?: string;
  /** Timeout guard for the child. */
  readonly timeoutMs?: number;
}

export interface WrapperRunResult {
  readonly exitCode: number | null;
  readonly stdout: string;
  readonly stderr: string;
  /** Parsed `$GITHUB_OUTPUT` lines (null when `env.GITHUB_OUTPUT` unset). */
  readonly outputs: Record<string, string> | null;
  readonly outputRaw: string | null;
}

/** Parse `$GITHUB_OUTPUT`-style `name=value` lines (last write wins). */
export function parseGithubOutput(text: string): Record<string, string> {
  const out: Record<string, string> = {};
  for (const line of text.split("\n")) {
    const idx = line.indexOf("=");
    if (idx > 0) {
      out[line.slice(0, idx)] = line.slice(idx + 1);
    }
  }
  return out;
}

/** Spawn the built wrapper and capture stdout/stderr/exit + `$GITHUB_OUTPUT`. */
export function runWrapper(args: readonly string[], opts: RunWrapperOptions = {}): Promise<WrapperRunResult> {
  const entry = opts.entry ?? CI_MAIN_PATH;
  const env: Record<string, string> = { PATH: process.env["PATH"] ?? "" };
  for (const [key, value] of Object.entries(opts.env ?? {})) {
    if (value !== undefined) {
      env[key] = value;
    }
  }
  return new Promise((resolvePromise, rejectPromise) => {
    const child = spawn(process.execPath, [entry, ...args], {
      cwd: opts.cwd ?? pkgRoot,
      env,
      stdio: ["ignore", "pipe", "pipe"],
    });
    let stdout = "";
    let stderr = "";
    child.stdout.on("data", (chunk: Buffer) => (stdout += chunk.toString("utf8")));
    child.stderr.on("data", (chunk: Buffer) => (stderr += chunk.toString("utf8")));
    const timer = setTimeout(() => child.kill("SIGKILL"), opts.timeoutMs ?? 60_000);
    child.on("error", rejectPromise);
    child.on("close", (code) => {
      clearTimeout(timer);
      const outputFile = env["GITHUB_OUTPUT"];
      const outputRaw = outputFile !== undefined && existsSync(outputFile) ? readFileSync(outputFile, "utf8") : null;
      resolvePromise({
        exitCode: code,
        stdout,
        stderr,
        outputs: outputRaw === null ? null : parseGithubOutput(outputRaw),
        outputRaw,
      });
    });
  });
}

// ──────────────────────────────────────────────────────────────── githubEnv

export interface GithubEnvSpec {
  readonly eventName: "pull_request" | "push";
  readonly baseRef?: string;
  readonly refName?: string;
  readonly output?: string;
  readonly workspace?: string;
}

/** Construct the GITHUB_* env view a Actions runner would pass through. */
export function githubEnv(spec: GithubEnvSpec): Record<string, string> {
  const env: Record<string, string> = {
    GITHUB_ACTION: "1",
    GITHUB_EVENT_NAME: spec.eventName,
  };
  if (spec.baseRef !== undefined) env["GITHUB_BASE_REF"] = spec.baseRef;
  if (spec.refName !== undefined) env["GITHUB_REF_NAME"] = spec.refName;
  if (spec.output !== undefined) env["GITHUB_OUTPUT"] = spec.output;
  if (spec.workspace !== undefined) env["GITHUB_WORKSPACE"] = spec.workspace;
  return env;
}
