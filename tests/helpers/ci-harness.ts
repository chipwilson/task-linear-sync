/**
 * T012 — Shared hermetic harness for 013 CI-enforcement tests.
 *
 * Builds on the 009 `cli-harness` base (`buildCliWorld`/`writeDriver`
 * conventions, research R12). The wrapper is tested from OUTSIDE: unit tiers
 * inject fixture reports through the `reportPath` seam; e2e spawns the REAL
 * built wrapper (`dist/ci/main.js`) against fake published-CLI entries built
 * over 009/008 world fixtures.
 *
 * Public API
 * - `writeCliEntry(entryPath, opts)` — emits a `cli-entry.mjs` that acts as the
 *   published bin: wires the 007 fake port + `fixedClock` + temp state dir from
 *   a world fixture, runs the REAL CLI core via `task-linear-sync/cli`
 *   `runCli` with argv from `process.argv.slice(2)` (`command [repo]
 *   [--config]`), RAW stdout posture (no `OUT|` prefixes — `check` emits its
 *   single JSON object untouched), appends each invocation's argv to a JSONL
 *   census file, mirrors stdout/stderr, and sets `process.exitCode`.
 * - `runWrapper(args, opts)` — spawns `node dist/ci/main.js` with the given
 *   args + constructed env view (hermetic: PATH only from the parent), returns
 *   `{ exitCode, stdout, stderr, outputs }` (outputs = parsed `$GITHUB_OUTPUT`
 *   file, `null` when no output file was requested).
 * - `githubEnv({ eventName, baseRef?, refName?, output? })` — GITHUB_* builder.
 * - `fixtureReport(name)` / `copyFixtureReport(name, destDir)` — corpus access.
 * - `ciWorldDir(name)` — named world under `tests/fixtures/cli/worlds/` (the
 *   009 corpus is reused, no copies).
 * - re-exports `hashTree` / `listTree` (zero-write proofs).
 */
